from __future__ import annotations

from structforge.models import (
    FieldKind,
    PointerChain,
    SdkSpec,
    StructDef,
    StructField,
    validate_spec,
)


def _cpp_scalar_type(kind: FieldKind) -> str:
    return {
        FieldKind.VPTR: "std::uint64_t",
        FieldKind.PTR64: "std::uint64_t",
        FieldKind.CSTR_PTR: "std::uint64_t",
        FieldKind.STD_VECTOR: "RawVectorView",
        FieldKind.F64: "double",
        FieldKind.I64: "std::int64_t",
        FieldKind.U64: "std::uint64_t",
        FieldKind.F32: "float",
        FieldKind.I32: "std::int32_t",
        FieldKind.U32: "std::uint32_t",
        FieldKind.U16: "std::uint16_t",
        FieldKind.U8: "std::uint8_t",
        FieldKind.BOOL: "bool",
    }[kind]


def _safe_comment(text: str) -> str:
    return text.replace("\r", " ").replace("\n", " ")


def _emit_field(fld: StructField) -> str:
    if fld.kind == FieldKind.CHAR_ARRAY:
        return f"    char {fld.name}[{fld.size}]{{}};"
    if fld.kind == FieldKind.PAD:
        return f"    std::uint8_t {fld.name}[{fld.size}]{{}};"
    cpp_ty = _cpp_scalar_type(fld.kind)
    comment = ""
    if fld.kind == FieldKind.VPTR and fld.target_type:
        comment = (
            f" // RTTI: {_safe_comment(fld.target_type)} (vtable RVA 0x{fld.vtable_rva or 0:x})"
        )
    elif fld.kind == FieldKind.PTR64 and fld.target_type:
        comment = f" // -> {_safe_comment(fld.target_type)}*"
    elif fld.kind == FieldKind.STD_VECTOR and fld.elem_stride:
        comment = f" // elem_stride={fld.elem_stride}B"
    return f"    {cpp_ty} {fld.name}{{}};{comment}"


def _emit_struct(st: StructDef) -> list[str]:
    lines: list[str] = []
    if st.demangled_rtti:
        bases = (
            f" : {', '.join(_safe_comment(b) for b in st.base_classes)}" if st.base_classes else ""
        )
        lines.append(f"// RTTI: {_safe_comment(st.demangled_rtti)}{bases}")
    lines.append(f"struct {st.name} {{")
    for fld in st.fields:
        lines.append(_emit_field(fld))
    lines.append("};")
    lines.append(f"static_assert(std::is_standard_layout_v<{st.name}>);")
    lines.append(f"static_assert(sizeof({st.name}) == 0x{st.size:x}u);")
    lines.append(f"static_assert(alignof({st.name}) == {st.alignment}u);")
    for fld in st.fields:
        lines.append(f"static_assert(offsetof({st.name}, {fld.name}) == 0x{fld.offset:x}u);")
    lines.append("")
    return lines


def _emit_chain(ch: PointerChain) -> list[str]:
    lines: list[str] = []
    offsets_lit = ", ".join(f"0x{off:x}ULL" for off in ch.offsets)
    lines.append(
        f"inline constexpr std::array<std::uint64_t, {len(ch.offsets)}> "
        f"CHAIN_{ch.name}_OFFSETS{{ {{ {offsets_lit} }} }};"
    )
    cpp_ty = _cpp_scalar_type(ch.field_kind)
    lines.append("template <MemoryReader R>")
    lines.append(
        f"[[nodiscard]] inline std::optional<{cpp_ty}> read_chain_{ch.name}("
        "const R& reader, std::uint64_t image_base) noexcept {"
    )
    lines.append(
        f"    const auto addr = walk_chain_addr(reader, image_base + 0x{ch.root_rva:x}ULL, "
        f"std::span<const std::uint64_t>{{CHAIN_{ch.name}_OFFSETS}});"
    )
    lines.append("    if (!addr.has_value()) {")
    lines.append("        return std::nullopt;")
    lines.append("    }")
    lines.append(f"    return read_val<{cpp_ty}>(reader, *addr);")
    lines.append("}")
    lines.append("")
    return lines


def generate_cpp_header(spec: SdkSpec) -> str:
    validate_spec(spec)
    lines: list[str] = [
        "#pragma once",
        f"// Generated by structforge for SDK '{spec.name}' ({_safe_comment(spec.module_name)})",
        "",
        "#include <array>",
        "#include <concepts>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <cstring>",
        "#include <optional>",
        "#include <span>",
        "#include <type_traits>",
        "",
        "namespace structforge_gen {",
        "",
        "#ifndef STRUCTFORGE_GEN_RUNTIME_HELPERS",
        "#define STRUCTFORGE_GEN_RUNTIME_HELPERS",
        "",
        "struct RawVectorView {",
        "    std::uint64_t begin_va{0};",
        "    std::uint64_t end_va{0};",
        "    std::uint64_t cap_va{0};",
        "",
        "    [[nodiscard]] constexpr std::uint64_t byte_len() const noexcept {",
        "        return end_va >= begin_va ? (end_va - begin_va) : 0u;",
        "    }",
        "",
        "    [[nodiscard]] constexpr std::size_t count(std::size_t elem_size) const noexcept {",
        "        return elem_size > 0u ? static_cast<std::size_t>(byte_len() / elem_size) : 0u;",
        "    }",
        "};",
        "static_assert(sizeof(RawVectorView) == 24u && alignof(RawVectorView) == 8u);",
        "",
        "template <typename R>",
        "concept MemoryReader = requires(const R& r, std::uint64_t va, std::span<std::uint8_t> out) {",
        "    { r.read(va, out) } -> std::convertible_to<bool>;",
        "};",
        "",
        "struct RegionView {",
        "    std::uint64_t base_va{0};",
        "    std::span<const std::uint8_t> data{};",
        "};",
        "",
        "class SpanSnapshotReader {",
        "public:",
        "    explicit constexpr SpanSnapshotReader(std::span<const RegionView> regions) noexcept",
        "        : regions_(regions) {}",
        "",
        "    [[nodiscard]] bool read(std::uint64_t va, std::span<std::uint8_t> out) const noexcept {",
        "        for (const auto& reg : regions_) {",
        "            if (va >= reg.base_va && va - reg.base_va <= reg.data.size()) {",
        "                const std::size_t off = static_cast<std::size_t>(va - reg.base_va);",
        "                if (out.size() <= reg.data.size() - off) {",
        "                    if (!out.empty()) {",
        "                        std::memcpy(out.data(), reg.data.data() + off, out.size());",
        "                    }",
        "                    return true;",
        "                }",
        "            }",
        "        }",
        "        return false;",
        "    }",
        "",
        "private:",
        "    std::span<const RegionView> regions_{};",
        "};",
        "",
        "template <typename T, MemoryReader R>",
        "[[nodiscard]] inline std::optional<T> read_val(const R& reader, std::uint64_t va) noexcept {",
        "    static_assert(std::is_trivially_copyable_v<T>);",
        "    std::array<std::uint8_t, sizeof(T)> buf{};",
        "    if (!reader.read(va, std::span<std::uint8_t>{buf})) {",
        "        return std::nullopt;",
        "    }",
        "    T val{};",
        "    std::memcpy(&val, buf.data(), sizeof(T));",
        "    return val;",
        "}",
        "",
        "template <MemoryReader R>",
        "[[nodiscard]] inline std::optional<std::uint64_t> walk_chain_addr(",
        "    const R& reader,",
        "    std::uint64_t root_va,",
        "    std::span<const std::uint64_t> offsets) noexcept {",
        "    if (offsets.empty()) {",
        "        return std::nullopt;",
        "    }",
        "    auto ptr = read_val<std::uint64_t>(reader, root_va);",
        "    if (!ptr.has_value() || *ptr == 0u) {",
        "        return std::nullopt;",
        "    }",
        "    for (std::size_t i = 0; i + 1u < offsets.size(); ++i) {",
        "        ptr = read_val<std::uint64_t>(reader, *ptr + offsets[i]);",
        "        if (!ptr.has_value() || *ptr == 0u) {",
        "            return std::nullopt;",
        "        }",
        "    }",
        "    return *ptr + offsets.back();",
        "}",
        "",
        "#endif // STRUCTFORGE_GEN_RUNTIME_HELPERS",
        "",
    ]

    for st in spec.structs:
        lines.extend(_emit_struct(st))

    for ch in spec.pointer_chains:
        lines.extend(_emit_chain(ch))

    lines.append("} // namespace structforge_gen")
    lines.append("")
    return "\n".join(lines)
